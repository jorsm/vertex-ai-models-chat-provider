const fs = require("node:fs/promises");
const path = require("node:path");
const { parseEnv } = require("node:util");
const { DEFAULTS } = require("./support.cjs");

const ENV_KEYS = {
    VERTEX_LIVE_PROJECT_ID: "project",
    VERTEX_LIVE_EXPECTED_ACCOUNT: "expectedAccount",
    VERTEX_LIVE_ADC_FILE: "adcFile",
    VERTEX_LIVE_REGION: "region",
    VERTEX_LIVE_REQUEST_TIMEOUT_SECONDS: "requestTimeoutSeconds",
    VERTEX_LIVE_HOST_TIMEOUT_SECONDS: "hostTimeoutSeconds",
    VERTEX_LIVE_VSCODE_VERSION: "vscodeVersion",
    VERTEX_LIVE_VSCODE_EXECUTABLE: "vscodeExecutable",
    VERTEX_LIVE_VSIX: "vsix",
    VERTEX_LIVE_REPORT_PATH: "report",
};

function isCi(environment) {
    return Boolean(environment.CI || environment.GITHUB_ACTIONS);
}

function environmentSettings(environment) {
    const settings = { models: {} };
    if (environment.GOOGLE_APPLICATION_CREDENTIALS !== undefined) settings.adcFile = environment.GOOGLE_APPLICATION_CREDENTIALS;
    for (const [
        variable,
        key,
    ] of Object.entries(ENV_KEYS)) {
        if (environment[variable] === undefined) continue;
        const value = environment[variable];
        if (key === "requestTimeoutSeconds" || key === "hostTimeoutSeconds") {
            if (!/^\d+$/.test(value)) throw new Error(`${variable} must be a positive integer.`);
            settings[key] = Number(value);
        } else settings[key] = value;
    }
    for (const provider of Object.keys(DEFAULTS.models)) {
        const value = environment[`VERTEX_LIVE_${provider.toUpperCase()}_MODEL`];
        if (value !== undefined) settings.models[provider] = value;
    }
    return settings;
}

async function loadConfiguration({ values = {}, environment = process.env, root = path.resolve(__dirname, "../..") } = {}) {
    let local = {};
    // A repository-local file must never select identities/projects for hosted CI.
    if (!isCi(environment) || values["env-file"]) {
        const file = path.resolve(root, values["env-file"] || ".env");
        try {
            local = parseEnv(await fs.readFile(file, "utf8"));
        } catch (error) {
            if (error.code !== "ENOENT" || values["env-file"]) throw new Error("Cannot read the live-test environment file.");
        }
    }
    const layers = [
        environmentSettings(local),
        environmentSettings(environment),
    ];
    const configuration = { ...DEFAULTS, models: { ...DEFAULTS.models } };
    for (const layer of layers) {
        Object.assign(configuration, { ...layer, models: { ...configuration.models, ...layer.models } });
    }
    for (const [
        flag,
        key,
    ] of Object.entries({ project: "project", "expected-account": "expectedAccount", "adc-file": "adcFile", region: "region", "vscode-version": "vscodeVersion", "vscode-executable": "vscodeExecutable", vsix: "vsix", report: "report" })) {
        if (values[flag] !== undefined) configuration[key] = values[flag];
    }
    for (const provider of Object.keys(DEFAULTS.models)) if (values[`${provider}-model`] !== undefined) configuration.models[provider] = values[`${provider}-model`];
    if (isCi(environment) && environment.GOOGLE_APPLICATION_CREDENTIALS && configuration.adcFile && path.resolve(root, environment.GOOGLE_APPLICATION_CREDENTIALS) !== path.resolve(root, configuration.adcFile)) {
        throw new Error("CI ADC overrides conflict with GOOGLE_APPLICATION_CREDENTIALS. Use the credential file generated by the authentication action.");
    }
    if (typeof configuration.project !== "string" || !/^[a-z][a-z0-9-]{4,61}[a-z0-9]$/.test(configuration.project)) throw new Error("Set VERTEX_LIVE_PROJECT_ID in .env or the injected environment, or pass --project.");
    if (typeof configuration.region !== "string" || !/^[a-z0-9-]+$/.test(configuration.region)) throw new Error("Set a valid VERTEX_LIVE_REGION.");
    if (typeof configuration.expectedAccount !== "string") throw new Error("VERTEX_LIVE_EXPECTED_ACCOUNT must be a string.");
    for (const model of Object.values(configuration.models)) if (typeof model !== "string" || !model.trim()) throw new Error("Each provider needs an explicit nonempty model ID.");
    for (const key of [
        "requestTimeoutSeconds",
        "hostTimeoutSeconds",
    ])
        if (!Number.isInteger(configuration[key]) || configuration[key] < 1 || configuration[key] > 3600) throw new Error(`${key} must be between 1 and 3600.`);
    if (configuration.adcFile) {
        configuration.adcFile = path.resolve(root, configuration.adcFile);
        try {
            await fs.access(configuration.adcFile);
        } catch {
            throw new Error("The configured ADC file is unavailable. Check VERTEX_LIVE_ADC_FILE or GOOGLE_APPLICATION_CREDENTIALS.");
        }
    }
    return configuration;
}

// Reports saved by CI can be shared without publishing configured project/account/path values.
function publicReport(report, configuration) {
    const privateValues = [
        configuration.project,
        configuration.expectedAccount,
        configuration.adcFile,
        report.authentication?.email,
    ].filter(Boolean);
    const redact = (value) => {
        if (typeof value === "string") return privateValues.reduce((text, privateValue) => text.split(privateValue).join("[REDACTED]"), value);
        if (Array.isArray(value)) return value.map(redact);
        if (value && typeof value === "object")
            return Object.fromEntries(
                Object.entries(value).map(
                    ([
                        key,
                        item,
                    ]) => [
                        key,
                        redact(item),
                    ],
                ),
            );
        return value;
    };
    return redact(report);
}

module.exports = { loadConfiguration, publicReport, isCi };
